// StackDirectNodes 按当前保存的授权生成外部上游节点，不依赖本机进程的应用状态。
func StackDirectNodes(doc *Document) ([]sub.Node, error) {
	nodes := []sub.Node{}
	for _, stack := range doc.Stacks {
		if !stack.Enabled || len(stack.DirectUsers) == 0 {
			continue
		}
		suffix := stack.DirectSuffix
		if suffix == "" {
			suffix = DefaultDirectSuffix
		}
		externalCount := 0
		for _, upstream := range stack.Mihomo.Upstreams {
			if upstream.Type == "raw" {
				externalCount++
			}
		}
		for _, name := range stack.DirectUsers {
			index := doc.UserByName(name)
			if index < 0 {
				return nil, fmt.Errorf("stack %s references a missing direct user: %s", stack.Name, name)
			}
			user := doc.Users[index]
			if slices.Contains(user.PausedStacks, stack.Name) {
				continue
			}
			for _, upstream := range stack.Mihomo.Upstreams {
				if upstream.Type != "raw" {
					continue
				}
				protocol, _ := upstream.Config.Get("type")
				remark, region, err := directSubscriptionName(doc, stack, user, protocol)
				if err != nil {
					return nil, err
				}
				if externalCount > 1 {
					remark += " · " + upstream.Name
				}
				remark += suffix
				id := stack.Name + ":direct:" + upstream.Name + ":" + name
				config := DirectNodeConfig(stack, name, upstream)
				node, err := (ManualNode{User: name, Remark: remark, Region: region, Config: config}).directNode(id, id)
				if err != nil {
					return nil, fmt.Errorf("stack %s upstream %s: %w", stack.Name, upstream.Name, err)
				}
				nodes = append(nodes, node)
			}
		}
	}
	return nodes, nil
}

// directServerOnlyFields 是只对服务器拨号有意义的字段，下发前一律删除。
var directServerOnlyFields = []string{"dialer-proxy", "interface-name", "routing-mark"}

// directOverrideForbidden 是覆盖中不允许出现的字段：协议和名称由上游与订阅规则决定，
// 服务器专用字段和订阅内部字段在生成节点时会被丢弃，写入覆盖没有效果。
var directOverrideForbidden = map[string]string{
	"type":           "the protocol is defined by the upstream",
	"name":           "node names are generated by the subscription",
	"dialer-proxy":   "server-only fields are removed from direct nodes",
	"interface-name": "server-only fields are removed from direct nodes",
	"routing-mark":   "server-only fields are removed from direct nodes",
	"id":             "reserved for subscription metadata",
	"user":           "reserved for subscription metadata",
	"direct":         "reserved for subscription metadata",
	"tag":            "reserved for subscription metadata",
	"remark":         "reserved for subscription metadata",
	"region":         "reserved for subscription metadata",
}

// FindDirectOverride 返回 user 在 upstream 上的覆盖，没有时返回 nil。
func FindDirectOverride(stack Stack, user, upstream string) *DirectOverride {
	for index := range stack.DirectOverrides {
		override := &stack.DirectOverrides[index]
		if override.User == user && override.Upstream == upstream {
			return override
		}
	}
	return nil
}

// DirectNodeConfig 生成用户直连 upstream 时下发的节点字段：复制上游配置，用该用户的覆盖整体替换同名顶层字段，
// 最后删除服务器专用字段。不修改上游和覆盖本身。
func DirectNodeConfig(stack Stack, user string, upstream Upstream) RawMapping {
	config := upstream.Config.Clone()
	if override := FindDirectOverride(stack, user, upstream.Name); override != nil {
		config = mergeRawMapping(config, override.Config)
	}
	for _, key := range directServerOnlyFields {
		config.Delete(key)
	}
	return config
}

// validateDirectOverrides 校验覆盖引用的用户和上游，并确认合并后的节点仍能生成。
// 上游自身无效时只报告上游错误，不重复归到覆盖上。
func validateDirectOverrides(issues *Issues, path string, stack *Stack, directUsers map[string]bool) {
	seen := map[string]bool{}
	for index, override := range stack.DirectOverrides {
		field := fmt.Sprintf("%s.direct_overrides[%d]", path, index)
		valid := true
		if !directUsers[override.User] {
			issues.add(field+".user", "must be one of the direct users: %s", override.User)
			valid = false
		}
		upstreamIndex := slices.IndexFunc(stack.Mihomo.Upstreams, func(upstream Upstream) bool { return upstream.Name == override.Upstream })
		if upstreamIndex < 0 {
			issues.add(field+".upstream", "upstream does not exist: %s", override.Upstream)
			valid = false
		} else if stack.Mihomo.Upstreams[upstreamIndex].Type != "raw" {
			issues.add(field+".upstream", "must reference an external (raw) upstream: %s", override.Upstream)
			valid = false
		}
		key := override.User + "\x00" + override.Upstream
		if seen[key] {
			issues.add(field, "duplicate override for user %s on upstream %s", override.User, override.Upstream)
			valid = false
		}
		seen[key] = true
		if override.Config.IsZero() {
			issues.add(field+".config", "must override at least one field")
			continue
		}
		for position := 0; position+1 < len(override.Config.Node.Content); position += 2 {
			name := override.Config.Node.Content[position].Value
			if reason, forbidden := directOverrideForbidden[canonicalFieldName(name)]; forbidden {
				issues.add(field+".config", "field %s cannot be overridden: %s", name, reason)
				valid = false
			}
		}
		if !valid {
			continue
		}
		upstream := stack.Mihomo.Upstreams[upstreamIndex]
		if checkDirectConfig(override.User, DirectNodeConfig(Stack{}, override.User, upstream)) != nil {
			continue
		}
		if err := checkDirectConfig(override.User, DirectNodeConfig(*stack, override.User, upstream)); err != nil {
			issues.add(field+".config", "%s", err.Error())
		}
	}
}

// checkDirectConfig 按上游校验规则和直连节点生成规则检查节点字段。
func checkDirectConfig(user string, config RawMapping) error {
	if config.Node == nil {
		return fmt.Errorf("config is required")
	}
	var compiled domain.ClashUpstream
	if err := compiled.SetRawConfig(config.Node); err != nil {
		return err
	}
	if err := domain.ValidateRawProxyConfig(compiled.Config); err != nil {
		return err
	}
	_, err := (ManualNode{User: user, Remark: "direct", Config: config}).directNode("direct", "direct")
	return err
}

// mergeRawMapping 用 overlay 的顶层字段替换 base 中的同名字段，新字段按 overlay 的顺序追加到末尾。
// 订阅渲染同时接受连字符和下划线两种字段写法（例如 ws-opts 与 ws_opts），这里按同一字段处理：
// 替换第一处同名字段并删除其余写法，键名采用 overlay 的写法，避免两种写法同时存在时覆盖不生效。
func mergeRawMapping(base, overlay RawMapping) RawMapping {
	if overlay.Node == nil {
		return base
	}
	if base.Node == nil {
		return overlay.Clone()
	}
	for index := 0; index+1 < len(overlay.Node.Content); index += 2 {
		key, value := cloneNode(overlay.Node.Content[index]), cloneNode(overlay.Node.Content[index+1])
		name := canonicalFieldName(key.Value)
		replaced := false
		content := base.Node.Content[:0:0]
		for position := 0; position+1 < len(base.Node.Content); position += 2 {
			if canonicalFieldName(base.Node.Content[position].Value) != name {
				content = append(content, base.Node.Content[position], base.Node.Content[position+1])
				continue
			}
			if !replaced {
				content = append(content, key, value)
				replaced = true
			}
		}
		if !replaced {
			content = append(content, key, value)
		}
		base.Node.Content = content
	}
	return base
}

// canonicalFieldName 把字段名中的下划线统一为连字符，用于识别同一字段的两种写法。
func canonicalFieldName(name string) string {
	return strings.ReplaceAll(name, "_", "-")
}

// directSubscriptionName 使用包含该用户的首个订阅入站；仅授权直连时不借用无关入站模板。
func directSubscriptionName(doc *Document, stack Stack, user User, protocol string) (string, string, error) {
	inbound := Inbound{Name: "direct", Protocol: protocol}
	var ref *UserRef
	for candidateIndex := range stack.Xray.Inbounds {
		candidate := &stack.Xray.Inbounds[candidateIndex]
		if !candidate.Sub {
			continue
		}
		for refIndex := range candidate.Users {
			if candidate.Users[refIndex].User == user.Name {
				inbound = *candidate
				ref = &candidate.Users[refIndex]
				break
			}
		}
		if ref != nil {
			break
		}
	}
	remark, display, profile := inbound.Remark, user.DisplayTemplate, DefaultProfile
	if ref != nil {
		if ref.Profile != "" && ref.Profile != DefaultProfile {
			profile = ref.Profile
			for _, candidate := range user.Profiles {
				if candidate.Name == profile {
					if candidate.Remark != "" {
						remark = candidate.Remark
					}
					display = candidate.DisplayTemplate
					break
				}
			}
		}
		if ref.Remark != "" {
			remark = ref.Remark
		}
		if ref.DisplayTemplate != "" {
			display = ref.DisplayTemplate
		}
	}
	globalDisplay := ""
	if doc.Settings != nil {
		globalDisplay = doc.Settings.Subscription.DisplayTemplate
	}
	name, err := sub.SubscriptionRemark(stack.Name, compileInbound(inbound), user.Name, domain.NormalizeUserProfile(profile), remark,
		display, inbound.DisplayTemplate, globalDisplay)
	return name, inbound.Region, err
}
